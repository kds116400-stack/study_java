package src.ui.form;

import javax.swing.*;

/**
 * Form 인터페이스는 공통적으로 사용되는 GUI 폼 요소의 상수와 정적 메서드(static method)를 정의한다.
 * 
 * 주로 뼈대(공통) GUI 프레임/버튼/필드 규격을 고정 순위로 제공한다.
 */
public interface Form {

    // ----------------------------------------------------------------
    // [프레임(Frame) 관련 상수: 모든 프레임에 동일한 위치/크기로 사용]
    // ----------------------------------------------------------------
    int F = 0;        // 프레임 시작 X 또는 Y 좌표(항상 0,0 좌상단 기준)
    int W = 360;      // 프레임의 기본 너비(가로 픽셀)
    int H = 600;      // 프레임의 기본 높이(세로 픽셀)

    // ----------------------------------------------------------------
    // [버튼(Button) 관련 상수: 공통 버튼 규격 및 위치]
    // ----------------------------------------------------------------
    int BT_X = 100;   // 버튼의 X(가로) 좌표(모든 주요 버튼 동일 기준)
    int BT_Y = 70;    // 첫번째 버튼의 Y(세로) 좌표(다음 버튼은 간격만큼 +)
    int BT_W = 140;   // 버튼의 표준 너비
    int BT_H = 60;    // 버튼의 표준 높이

    // ----------------------------------------------------------------
    // [글자만 있는 버튼 BACK 위치 상수]
    // ----------------------------------------------------------------
    int BACK = 480;   // '뒤로(BACK)' 등 단순 텍스트 버튼의 Y 좌표 기준(프레임 하단 고정)

    // ----------------------------------------------------------------
    // [FormField(입력 필드) 관련 상수: 개인 정보/입력창 등에서 사용]
    // ----------------------------------------------------------------
    int FF_W = 330;   // FormField(입력박스 등)의 기본 너비
    int FF_H = 50;    // FormField(입력박스 등)의 기본 높이

    /**
     * 글자만 표시되는(테두리, 배경 없는) JButton 를 생성해서 반환.
     * 주로 취소/뒤로/로그아웃 버튼처럼 별도 스타일링 없이 사용할 때 쓴다.
     * 
     * @param text 버튼에 실제 표시할 텍스트(라벨)
     * @param y    버튼의 Y 좌표(위치); X, W, H는 상수(BT_X, BT_W, FF_H) 사용
     * @return JLabel처럼 평면적인 스타일의 JButton 객체(커스텀된)
     */
    static JButton clearButton(String text, int y) {
        JButton bt = new JButton(text);           // 전달받은 텍스트로 버튼 생성
        bt.setBorderPainted(false);               // 버튼 외곽선(테두리) 제거
        bt.setContentAreaFilled(false);           // 버튼 내부 배경색/배경 채우기 비활성화
        bt.setFocusPainted(false);                // 버튼 선택 시 파란 테두리 등 포커스 효과 제거
        bt.setBounds(BT_X, y, BT_W, FF_H);        // 위치(X는 고정, Y는 파라미터), 버튼 크기(폭:BT_W, 높이:FF_H) 지정
        return bt;                                // 커스텀 버튼 반환
    }

    /**
     * 공통 규격의 JFrame(윈도우 창)을 생성하여 반환한다.
     * 
     * - 프레임의 제목(상단 타이틀 바)은 text 파라미터로 지정
     * - 위치(0, 0) 및 크기(W*H) 고정, 배치관리자 해제(null, 절대 좌표 직접 설정)
     * - 닫기 버튼 클릭 시 프로그램을 완전히 종료(EXIT_ON_CLOSE)
     * 
     * @param text 프레임 타이틀 문자열(상단 표시 제목)
     * @return 생성 및 초기화 완료된 JFrame 객체
     */
    static JFrame setFrame(String text){
        JFrame frame = new JFrame(text);                   // 제목으로 프레임(윈도우) 생성
        frame.setBounds(F, F, W, H);                      // 프레임 위치: 좌상단(0,0), 크기: W x H
        frame.setLayout(null);                            // 배치 관리자 사용 안 함(컴포넌트 절대좌표 직접 지정, setBounds필수)
        frame.setDefaultCloseOperation(JFrame.EXIT_ON_CLOSE); // 창 닫기 → 전체 애플리케이션 종료
        return frame;                                     // 완성된 프레임 반환
    }
}